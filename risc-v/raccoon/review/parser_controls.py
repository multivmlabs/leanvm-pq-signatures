#!/usr/bin/env python3
"""Construct valid boundary inputs with the independent Python reference.

These algebraic zero-public-key inputs isolate encoding boundaries. They are
never generated by the benchmark corpus and are not performance experiments.
"""
from pathlib import Path
from hashlib import sha256, shake_256
import json
import sys

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
sys.path.insert(0, str(ROOT / "vendor/raccoon/ref-py"))
from racc_api import raccoon_128_1 as scheme
from polyr import mat_ntt, mul_mat_vec_ntt, ntt, intt, poly_rshift, poly_add

seed = bytes(scheme.as_sz)
pk = scheme.encode_pk((seed, [[0] * scheme.n for _ in range(scheme.k)]))
message = sha256(b"parser control, never benchmark material").digest()
mu = scheme._buff_mu(shake_256(pk).digest(scheme.tr_sz), message)
h = [[0] * scheme.n for _ in range(scheme.k)]
matrix = mat_ntt(scheme._expand_a(seed))
cases = {}
for name in ["byte-aligned", "exact-full", "hint-l2-fail", "hint-inf-fail", "response-inf-fail"]:
    h = [[0] * scheme.n for _ in range(scheme.k)]
    if name != "exact-full":
        z = [[0] * scheme.n for _ in range(scheme.ell)]
    else:
        z = [[(2 if i * scheme.n + j < 1312 else 1) << 40
              for j in range(scheme.n)] for i in range(scheme.ell)]
    if name == "hint-l2-fail":
        h = [[1] * scheme.n for _ in range(scheme.k)]
    elif name == "hint-inf-fail":
        h[0][0] = 3
    elif name == "response-inf-fail":
        z[0][0] = scheme.Boo + 1
    expected_valid = name in ("byte-aligned", "exact-full")
    assert scheme._check_bounds(h, z) == expected_valid
    y = mul_mat_vec_ntt(matrix, [ntt(v.copy()) for v in z])
    w = []
    for i, v in enumerate(y):
        intt(v)
        qw = scheme.q >> scheme.nuw
        w.append(poly_add(poly_rshift(v, scheme.nuw, qw), h[i], qw))
    sig = scheme.encode_sig((scheme._chal_hash(mu, w), h, z))
    expected = len(sig)
    if name == "byte-aligned": assert expected == 10848
    elif name == "exact-full": assert expected == scheme.sig_sz
    assert expected <= scheme.sig_sz
    sig = sig.ljust(scheme.sig_sz, b"\0")
    assert scheme.byte_verify(message, sig, pk) == expected_valid
    encoded = pk + message + sig
    path = HERE.parent / "host/testdata" / (name + ".bin")
    if path.exists():
        assert path.read_bytes() == encoded
    else:
        path.write_bytes(encoded)
    cases[name] = {"encoded_payload_bytes": expected,
                   "python_reference_accepts": expected_valid,
                   "input_sha256": sha256(encoded).hexdigest()}
(HERE / "parser-controls.json").write_text(json.dumps({"schema": 1, "cases": cases,
    "excluded_from_benchmarks": True}, indent=2) + "\n")
print(json.dumps(cases, indent=2))
