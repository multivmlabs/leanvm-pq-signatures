#!/usr/bin/env python3
"""Byte-for-byte official C/Python interoperability controls, no benchmarking."""
from pathlib import Path
from hashlib import sha256, shake_256
import json
import sys

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
sys.path.insert(0, str(ROOT / "vendor/raccoon/ref-py"))
from racc_api import raccoon_128_1 as scheme
from nist_kat_drbg import NIST_KAT_DRBG

fixture = json.loads((HERE / "fixture-0.json").read_text())
pk = bytes.fromhex(fixture["compact_public_key_hex"])
msg = bytes.fromhex(fixture["message_hex"])
sig = bytes.fromhex(fixture["compact_signature_hex"])
assert scheme.byte_verify(msg, sig, pk)
assert not scheme.byte_verify(bytes([msg[0] ^ 1]) + msg[1:], sig, pk)

# Recreate the fixture keygen/signing RNG independently in the Python reference.
seed = b"pqbench/raccoon1281/v1".ljust(32, b"\0")
entropy = shake_256(seed).digest(48)
message_seed = bytearray(seed)
message_seed[21] = ord("m")
assert shake_256(message_seed).digest(32) == msg
scheme.set_random(NIST_KAT_DRBG(entropy).random_bytes)
python_pk, python_sk = scheme.byte_keygen()
python_sig = scheme.byte_signature(msg, python_sk)
assert python_pk == pk
assert python_sig == sig

# First official NIST KAT input is generated by the prescribed AES-CTR DRBG.
kat = json.loads((HERE / "nist-kat-0.json").read_text())
drbg = NIST_KAT_DRBG(bytes(range(48)))
kat_seed, kat_message = drbg.random_bytes(48), drbg.random_bytes(33)
assert kat_seed.hex() == kat["seed"] and kat_message.hex() == kat["message"]
scheme.set_random(NIST_KAT_DRBG(kat_seed).random_bytes)
kat_pk, kat_sk = scheme.byte_keygen()
kat_sm = scheme.byte_sign(kat_message, kat_sk)
for name, actual in [("public_key", kat_pk), ("secret_key", kat_sk), ("signed_message", kat_sm)]:
    assert actual.hex() == kat[name], name
assert scheme.byte_open(kat_sm, kat_pk) == (True, kat_message)

result = {
    "schema": 1,
    "reference_commit": "e789b4b72a2b7e8a2205df49c487736985fc8417",
    "scheme": "Raccoon-128-1",
    "status": "passed",
    "checks": ["fixture accepted by independent Python reference", "changed message rejected",
               "fixture key and signature byte-for-byte C/Python agreement",
               "official first NIST KAT seed/message/keypair/signed-message C/Python agreement"],
    "fixture_sha256": sha256((HERE / "fixture-0.json").read_bytes()).hexdigest(),
    "nist_kat_sha256": sha256((HERE / "nist-kat-0.json").read_bytes()).hexdigest(),
    "benchmarks_run": False,
}
(HERE / "crosscheck.json").write_text(json.dumps(result, indent=2) + "\n")
print(json.dumps(result, indent=2))
