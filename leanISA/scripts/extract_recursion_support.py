#!/usr/bin/env python3
"""Extract the pinned generic recursive-verifier hint/layout dependency closure."""
import hashlib
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "vendor/leanVM/crates/rec_aggregation/src/aggregation.rs"
EXPECTED_SHA256 = "a3c6b3b6f42eb451f74c19da910aa25c47df1eb14f830aeb1f6988d6c8dee7d0"


def item(source, marker):
    start = source.index(marker)
    end = source.index("\n}\n", start) + 3
    return source[start:end]


def main():
    source = SOURCE.read_text()
    digest = hashlib.sha256(SOURCE.read_bytes()).hexdigest()
    if digest != EXPECTED_SHA256:
        raise SystemExit(f"Unexpected upstream aggregation.rs SHA-256 {digest}; review extraction against the new revision")
    generic_start = source.index("struct WhirShape {")
    generic_end = source.index("/// An edit to a node's hints:", generic_start)
    generic = source[generic_start:generic_end]
    generic = generic.replace("Result<(SubHints, DeferredSubproof), AggregationError>", "Result<(SubHints, DeferredSubproof), String>")
    generic = generic.replace("return Err(AggregationError::ChildOutOfRange {\n            log_committed: layout.shape.mu,\n        });", "return Err(format!(\"child outside recursive verifier range: log_committed={}, fits_buffers={}\", layout.shape.mu, fits));")
    generic = generic.replace("let bytecode_value = mle_eval_par(stacked_bytecode(), &bytecode_point);", "let child_bytecode = leanvm_core::cpu::bytecode_table(&program.prog);\n    let bytecode_value = mle_eval_par(&child_bytecode, &bytecode_point);")
    descriptors_start = source.index("struct CoordinateDescriptor {")
    placeholders = source[descriptors_start:source.index("fn placeholder_map(kbc:")]
    placeholders += item(source, "fn placeholder_map(kbc:")
    helpers = "\n\n".join(item(source, marker) for marker in [
        "fn count(n:", "fn dsl_u128(value:", "fn f192_literal(f:", "fn pack_hash_state(hash:", "fn pack_16_bytes(bytes:",
    ])
    license_text = (ROOT / "vendor/leanVM/LICENSE-MIT").read_text()
    header = "// Adapted from leanEthereum/leanVM aggregation.rs at commit\n// 575df819d9c857f38068cecf7b1640e0ce4bfb29.\n// Generated by scripts/extract_recursion_support.py; generic protocol logic is\n// copied without changes except typed errors and the explicit child-bytecode MLE.\n//\n" + "\n".join("// " + line if line else "//" for line in license_text.splitlines()) + "\n\n"
    imports = '''use std::collections::BTreeMap;
use std::ops::Range;

use lean_da::{DA_LOG_CELL, DA_LOG_K, DA_MAX_ROWS};
use leanvm_core::constraints::xi_offsets;
use leanvm_core::cpu::{KeccakLane, Program, from_scalar, keccak_value, scalar_proof};
use leanvm_core::leaf::{Block, Coord};
use leanvm_core::tables::N_TABLES;
use leanvm_core::transcript::{FiatShamirState, RATE_SCALARS};
use pcs::whir::{MAX_LOG_INV_RATE, MIN_LOG_INV_RATE};
use primitives::field::{F64, F192, G, g_pow};
use primitives::multilinear::mle_eval_par;
use signatures::{lean_sphincs, lean_xmss};

const VALCOL_FRAMEWORK: &str = "a framework block must not reference a virtual value column";
const RECURSION_AGG_LABEL: &[u8] = b"leanvm/recursion-aggregation/v1";
const DIGIT_GROUP: usize = 3;
const MAX_KEYS: usize = 1 << 16;
const MAX_RECURSIONS: usize = 16;
const CLAIM_GROUP: usize = 17;
const STATEMENT_HEADER: usize = 8;

struct DeferredSubproof {
    public_input: [F192; 2],
    bytecode_point: Vec<F192>,
    bytecode_value: F192,
}

/// The checked child's in-VM verification advice and its one deferred bytecode claim.
pub struct PreparedChild {
    pub public_input: [F192; 2],
    pub streams: BTreeMap<String, Vec<Vec<F192>>>,
    pub bytecode_point: Vec<F192>,
    pub bytecode_value: F192,
}

/// Layout constants for verifying proofs of a child with the given bytecode log size.
pub fn replacements(kbc: usize) -> BTreeMap<String, String> {
    placeholder_map(kbc)
}

/// Prepare advice only after checked verification; the wrapper must still verify it in-VM.
pub fn child_witness(
    program: &Program,
    public_input: [F192; 2],
    proof: &leanvm_core::cpu::Proof,
) -> Result<PreparedChild, String> {
    let summary = leanvm_core::cpu::verify(program, &public_input, proof)
        .map_err(|error| format!("invalid child proof: {error:?}"))?;
    let (hints, deferred) = gen_verify(program, public_input, &proof.stream, summary)?;
    let mut streams: BTreeMap<String, Vec<Vec<F192>>> = BTreeMap::new();
    for (name, entry) in hints {
        streams.entry(name.to_owned()).or_default().push(entry);
    }
    Ok(PreparedChild {
        public_input: deferred.public_input,
        streams,
        bytecode_point: deferred.bytecode_point,
        bytecode_value: deferred.bytecode_value,
    })
}

/// Test-only preparation of a deliberately inconsistent child, bypassing native
/// bytecode evaluation so the recursive verifier's deferred boundary is exercised.
/// This is never compiled into the experiment's production binary.
#[cfg(test)]
pub fn child_witness_replay_unchecked_for_test(
    traced_program: &Program,
    expected_bytecode: &verifier::Bytecode,
    public_input: [F192; 2],
    proof: &leanvm_core::cpu::Proof,
) -> Result<PreparedChild, String> {
    let summary = verifier::replay_unchecked(
        expected_bytecode,
        &leanvm_core::cpu::public_input_bytes(&public_input),
        &leanvm_core::cpu::scalar_proof(proof),
    )
    .map_err(|error| format!("test replay failed: {error:?}"))?;
    let (hints, deferred) = gen_verify(traced_program, public_input, &proof.stream, summary)?;
    let mut streams: BTreeMap<String, Vec<Vec<F192>>> = BTreeMap::new();
    for (name, entry) in hints {
        streams.entry(name.to_owned()).or_default().push(entry);
    }
    Ok(PreparedChild {
        public_input: deferred.public_input,
        streams,
        bytecode_point: deferred.bytecode_point,
        bytecode_value: deferred.bytecode_value,
    })
}
'''
    # scalar_proof is deliberately absent: cpu::verify performs its own checked conversion.
    imports = imports.replace(", scalar_proof", "")
    destination = ROOT / "src/recursion_support.rs"
    destination.write_text(header + imports + "\n" + helpers + "\n\n" + generic + "\n" + placeholders)
    subprocess.run(["rustfmt", "--edition", "2024", str(destination)], check=True)
    print(destination)


if __name__ == "__main__":
    main()
